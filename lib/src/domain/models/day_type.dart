/// The 5 training day-types for Undulating Periodization.
enum DayType {
  veryHeavy,  // Strength/Neuromuscular Recruitment (1–5 RM)
  moderate,   // Hypertrophy/Metabolic Stress (8–12 RM)
  power,      // Rate of Force Development (Low Reps Explosive)
  veryLight,  // Local Muscular Endurance (15–20+ RM)
  highLactic, // Metabolic Buffering (Circuits/EMOM)
}
